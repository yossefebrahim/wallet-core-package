import 'dart:convert';

import 'matrix.dart';
import 'variants.dart';

const String disclaimer =
    'Unofficial Dart/Flutter SDK for the open-source Trust Wallet Core library. Not affiliated with or endorsed by Trust Wallet.';

const String generatedBy = 'generated by `melos run gen:matrix` — do not edit';

const int schemaVersion = 1;

Map<String, Object?> _countsJson(Counts c) => {
  'generated': c.generated,
  'exposed': c.exposed,
  'tested': c.tested,
};

/// `docs/capability_matrix.json`: every (coin, operation, variant) with its
/// generated verdict and evidence, exposure, per-platform level, tested flag
/// and vectors, plus totals and the vector list check (c) compares against.
/// Deterministic: sorted, no timestamps, no paths.
String renderJson(Matrix matrix) {
  final document = <String, Object?>{
    'schema': schemaVersion,
    'generated_by': generatedBy,
    'disclaimer': disclaimer,
    'upstream': {'tag': matrix.upstream.tag, 'commit': matrix.upstream.commit},
    'levels': {
      '1': 'generated',
      '2': 'exposed',
      '3': 'verified on the platform by a vector',
    },
    'totals': {
      'operations': {
        for (final op in operations)
          op: _countsJson(matrix.operationTotals(op)),
      },
      'variants': [
        for (final t in matrix.variantTotals())
          {
            'operation': t.operation,
            'family': t.family,
            'variant': t.variant,
            ..._countsJson(t.counts),
          },
      ],
    },
    'conflicts': [
      for (final c in matrix.conflicts)
        {'coin': c.coin, 'operation': c.operation, 'detail': c.detail},
    ],
    'coins': {
      for (final row in matrix.coins)
        row.coin.id: {
          'name': row.coin.name,
          'blockchain': row.coin.blockchain,
          'family': row.family,
          'proto': row.proto,
          'deprecated': row.coin.deprecated,
          'operations': {
            for (final op in operations)
              op: _operationJson(row.operations[op]!),
          },
        },
    },
    'vectors': [
      for (final v in matrix.vectors)
        {
          'id': v.id,
          'coin': v.coin,
          'operation': v.operation,
          'variant': v.variant,
          'platforms': v.platforms,
        },
    ],
  };
  return '${const JsonEncoder.withIndent('  ').convert(document)}\n';
}

Map<String, Object?> _operationJson(OperationCell cell) => {
  'generated': cell.generated.name,
  'note': ?cell.note,
  'conflict': ?cell.conflict,
  'evidence': cell.evidence,
  'variants': {
    for (final v in cell.variants.values)
      v.variant: {
        'exposed': v.exposure,
        'levels': {for (final p in platforms) p: v.levelOn(p)},
        'tested': v.tested,
        'vectors': v.vectorIds,
      },
  },
};

const _operationText = {
  'address':
      'Generated when the registry lists at least one derivation for the coin '
      '(`TWAnyAddress`, `TWHDWallet` are per-coin through the registry).',
  'sign':
      'Generated when the coin\'s upstream proto package defines '
      '`SigningInput`. `TWAnySignerSign` is one global symbol and is never '
      'used as evidence.',
  'sign_message':
      'Generated when the coin\'s proto package defines `MessageSigningInput` '
      'and the generic message-signer probe (T2.9) agrees; a disagreement is '
      'a conflict.',
  'plan':
      'Generated when the coin\'s proto package defines `TransactionPlan`. '
      'Upstream documents `TWAnySignerPlan` for UTXO chains only; the proto is '
      'the per-coin evidence.',
  'compile':
      'Generated when the T2.9 compiler probe\'s static source rules and '
      'runtime calls agree that the coin has a transaction compiler. '
      '`aborts on malformed input` marks a compiler whose probe process died '
      'on malformed input: generated, but not safe to hand arbitrary bytes.',
};

String _countsLine(Counts c) =>
    '${c.generated} generated, ${c.exposed} exposed, ${c.tested} tested';

/// The text of one cell of a table.
String cellText(OperationCell cell, String variant) {
  switch (cell.generated) {
    case Generated.no:
      return '—';
    case Generated.conflict:
      return 'conflict';
    case Generated.yes:
      final v = cell.variants[variant]!;
      final note = cell.note == null ? '' : ', ${cell.note}';
      if (v.tested) return 'tested$note';
      final partial = v.verifiedOn.isEmpty
          ? ''
          : ' (verified on ${v.verifiedOn.join(', ')} only)';
      if (v.exposure != null) return 'exposed, unverified$partial$note';
      return 'generated$partial$note';
  }
}

String _columnTitle(String variant) => switch (variant) {
  anyVariant => 'status',
  'n/a' => 'address',
  _ => variant,
};

/// `docs/capability_matrix.md`.
///
/// Layout: totals first (per operation, then per variant), then one section
/// per operation. A section is a table per set of families that share variant
/// columns (a Bitcoin variant means nothing for an EVM chain), one row per
/// distinct pattern of cell texts with every coin that has it listed in the
/// row — 167 coins × 5 operations would otherwise be 835 near-identical rows.
/// The per-coin detail, with evidence, is `capability_matrix.json`.
String renderMarkdown(Matrix matrix) {
  final out = StringBuffer()
    ..writeln('# Capability matrix')
    ..writeln()
    ..writeln('> $generatedBy.')
    ..writeln()
    ..writeln(disclaimer)
    ..writeln()
    ..writeln(
      '**Upstream pin:** Tag ${matrix.upstream.tag}, Commit `${matrix.upstream.commit}`',
    )
    ..writeln()
    ..writeln('**Coins in the registry:** ${matrix.coins.length}')
    ..writeln()
    ..writeln('## How to read this')
    ..writeln()
    ..writeln(
      'Support is recorded per coin, operation and variant (PRD §13.1). A '
      'variant is a concrete transaction or message shape; one passing vector '
      'proves one variant, not a chain.',
    )
    ..writeln()
    ..writeln(
      '- **generated** — the coin\'s protobuf (or the T2.9 probe evidence) '
      'defines the operation and the registry lists the coin. Produced '
      'mechanically; says nothing about the SDK.',
    )
    ..writeln(
      '- **exposed, unverified** — the public SDK offers a typed or generic '
      'path, and no vector for this exact variant is confirmed on both '
      'Android and iOS.',
    )
    ..writeln(
      '- **tested** — a known-answer vector for this exact variant lists both '
      '`android` and `ios` in `platforms_verified`, and `matrix:check` '
      'confirms it against the CI results.',
    )
    ..writeln(
      '- **conflict** — the evidence sources disagree; reported, not '
      'resolved.',
    )
    ..writeln('- **—** — not generated for the coin.')
    ..writeln()
    ..writeln('## Totals')
    ..writeln()
    ..writeln(
      'Counted in coins. Per variant, a coin counts once for each variant '
      'cell it has.',
    )
    ..writeln()
    ..writeln('| operation | generated | exposed | tested |')
    ..writeln('|---|---|---|---|');
  for (final op in operations) {
    final c = matrix.operationTotals(op);
    out.writeln('| $op | ${c.generated} | ${c.exposed} | ${c.tested} |');
  }
  out
    ..writeln()
    ..writeln('| operation | family | variant | generated | exposed | tested |')
    ..writeln('|---|---|---|---|---|---|');
  for (final t in matrix.variantTotals()) {
    out.writeln(
      '| ${t.operation} | ${t.family} | ${t.variant} | ${t.counts.generated} | ${t.counts.exposed} | ${t.counts.tested} |',
    );
  }
  out
    ..writeln()
    ..writeln('### Conflicts')
    ..writeln();
  final conflicts = matrix.conflicts;
  if (conflicts.isEmpty) {
    out.writeln('None.');
  } else {
    for (final c in conflicts) {
      out.writeln('- `${c.coin}` ${c.operation}: ${c.detail}');
    }
  }

  for (final op in operations) {
    out
      ..writeln()
      ..writeln('## $op')
      ..writeln()
      ..writeln(_operationText[op])
      ..writeln()
      ..writeln('${_countsLine(matrix.operationTotals(op))}.');

    // Families that share variant columns share a table.
    final groups = <String, List<String>>{};
    for (final family in families) {
      final key = variantsOf(family, op).join('\u0000');
      groups.putIfAbsent(key, () => []).add(family);
    }
    for (final entry in groups.entries) {
      final columns = entry.key.split('\u0000');
      final groupFamilies = entry.value;
      out.writeln();
      if (groups.length > 1) {
        out
          ..writeln('### $op — ${groupFamilies.join(', ')}')
          ..writeln();
      }
      out
        ..writeln(
          '| family | coins | ${columns.map(_columnTitle).join(' | ')} |',
        )
        ..writeln('|---|---|${columns.map((_) => '---').join('|')}|');
      for (final family in groupFamilies) {
        final bySignature = <String, List<String>>{};
        for (final row in matrix.coins.where((r) => r.family == family)) {
          final texts = [
            for (final column in columns) cellText(row.operations[op]!, column),
          ];
          bySignature.putIfAbsent(texts.join(' | '), () => []).add(row.coin.id);
        }
        final signatures = bySignature.entries.toList()
          ..sort((a, b) => a.value.first.compareTo(b.value.first));
        for (final s in signatures) {
          out.writeln(
            '| $family | ${s.value.length}: ${s.value.join(', ')} | ${s.key} |',
          );
        }
      }
    }
  }
  return out.toString();
}
