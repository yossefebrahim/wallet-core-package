// The one Markdown table both DECISION-2 option documents embed.
//
// Unofficial Dart/Flutter SDK for the open-source Trust Wallet Core library.
// Not affiliated with or endorsed by Trust Wallet.
//
// Rows are the PRD §12.2 steps, columns are the targets, cells are
// pass/fail/skip/unmeasured with the measured value and a footnote pointing at
// the exact command that produced it. Output is a pure function of the result
// rows: same input, same bytes.

import 'results.dart';
import 'steps.dart';

/// Key for the `(check, target)` index. The separator is a character no check
/// name or target may contain, so the two halves can never run together.
String _key(String check, String target) => '$check\u0000$target';

class _Cell {
  _Cell(this.status, this.summary, this.command);

  CheckStatus status;
  String summary;
  String command;
}

/// Renders [rows] against [catalogue].
String renderReport(
  List<ResultRow> rows, {
  List<StepRow> catalogue = stepCatalogue,
  String title = 'PRD §12.2 packaging evaluation — measurement table',
}) {
  final measuredTargets = <String>{for (final row in rows) row.target};

  // A column is rendered when some result targets it, or when it is one of
  // the canonical consumer-app columns — the device work the decision needs to
  // see as outstanding is part of the table even before anyone runs it.
  final columns = <String>[
    ...artifactTargets.where(measuredTargets.contains),
    ...appTargets,
    ...otherTargets.where(
      (t) =>
          measuredTargets.contains(t) ||
          catalogue.any((r) => r.targets.contains(t)),
    ),
    ...(measuredTargets
        .where(
          (t) =>
              !artifactTargets.contains(t) &&
              !appTargets.contains(t) &&
              !otherTargets.contains(t),
        )
        .toList()
      ..sort()),
  ];

  final byCheckTarget = <String, List<ResultRow>>{};
  for (final row in rows) {
    byCheckTarget.putIfAbsent(_key(row.check, row.target), () => []).add(row);
  }

  final footnotes = <String, int>{};
  int footnoteFor(String command) {
    if (command.isEmpty) return 0;
    return footnotes.putIfAbsent(command, () => footnotes.length + 1);
  }

  final buffer = StringBuffer()
    ..writeln('# $title')
    ..writeln()
    ..writeln(
      'Unofficial Dart/Flutter SDK for the open-source Trust Wallet Core '
      'library. Not affiliated with or endorsed by Trust Wallet.',
    )
    ..writeln()
    ..writeln(
      'Generated by `melos run packaging:measure` '
      '(`tools/packaging_eval/bin/report.dart`). `unmeasured` is a check whose '
      'input does not exist on the machine that ran it; the footnote is the '
      'exact command that produces it when the input does. Library columns are '
      'the shipped file measured directly and have no debug/release axis; '
      'consumer-app columns are a built app.',
    )
    ..writeln();

  buffer.writeln('| PRD §12.2 step | ${columns.join(' | ')} |');
  buffer.writeln('|${'---|' * (columns.length + 1)}');

  final unresolved = <ResultRow>[];

  for (final specification in catalogue) {
    final cells = <String>[];
    for (final column in columns) {
      final matches =
          byCheckTarget[_key(specification.check, column)] ?? const [];
      if (matches.isEmpty) {
        if (!specification.targets.contains(column)) {
          cells.add('—');
          continue;
        }
        final n = footnoteFor(specification.command);
        cells.add('unmeasured [$n]');
        continue;
      }
      final cell = _aggregate(matches);
      final n = footnoteFor(cell.command);
      final value = cell.summary.isEmpty ? '' : ' ${cell.summary}';
      cells.add('${cell.status.name}$value${n == 0 ? '' : ' [$n]'}');
    }
    buffer.writeln(
      '| ${specification.step}. ${specification.label} '
      '(`${specification.check}`, ${specification.ownedBy}) | '
      '${cells.join(' | ')} |',
    );
  }

  // Any result whose (check, target) no catalogue row claims. Reported rather
  // than dropped: a silently discarded measurement is worse than an ugly one.
  final claimed = {
    for (final specification in catalogue)
      for (final target in specification.targets)
        _key(specification.check, target),
  };
  for (final row in rows) {
    if (!claimed.contains(_key(row.check, row.target))) {
      unresolved.add(row);
    }
  }

  buffer
    ..writeln()
    ..writeln('## Commands')
    ..writeln();
  final ordered = footnotes.entries.toList()
    ..sort((a, b) => a.value.compareTo(b.value));
  for (final entry in ordered) {
    buffer.writeln('[${entry.value}] `${entry.key}`');
    buffer.writeln();
  }

  final notes = rows.where((r) => r.notes.isNotEmpty).toList();
  if (notes.isNotEmpty) {
    buffer
      ..writeln('## Notes')
      ..writeln();
    for (final row in notes) {
      buffer.writeln('- **${row.check} / ${row.target}** — ${row.notes}');
    }
    buffer.writeln();
  }

  if (unresolved.isNotEmpty) {
    buffer
      ..writeln('## Results with no catalogue row')
      ..writeln();
    for (final row in unresolved) {
      buffer.writeln(
        '- `${row.check}` / `${row.target}`: ${row.status.name} '
        '${row.summary}',
      );
    }
    buffer.writeln();
  }

  return buffer.toString();
}

_Cell _aggregate(List<ResultRow> matches) {
  final sorted = [...matches]..sort((a, b) => a.summary.compareTo(b.summary));
  var status = sorted.first.status;
  for (final row in sorted.skip(1)) {
    status = CheckStatus.worst(status, row.status);
  }
  final summaries = <String>[];
  for (final row in sorted) {
    if (row.summary.isNotEmpty && !summaries.contains(row.summary)) {
      summaries.add(row.summary);
    }
  }
  final commands = <String>[];
  for (final row in sorted) {
    if (row.command.isNotEmpty && !commands.contains(row.command)) {
      commands.add(row.command);
    }
  }
  return _Cell(
    status,
    summaries.join('; '),
    commands.isEmpty ? '' : commands.join(' ; '),
  );
}
