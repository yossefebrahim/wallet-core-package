// The YAML subset, against the pubspec and pubspec.lock shapes it must read.
//
// Unofficial Dart/Flutter SDK for the open-source Trust Wallet Core library.
// Not affiliated with or endorsed by Trust Wallet.

import 'package:test/test.dart';
import 'package:wcf_tool_packaging_eval/mini_yaml.dart';

void main() {
  group('parseMiniYaml', () {
    test('nested maps indented by two spaces', () {
      final parsed = parseMiniYaml('''
name: wallet_core_flutter
environment:
  sdk: ^3.12.0
  flutter: ">=3.44.0"
dependencies:
  wallet_core_flutter_bindings:
    hosted: http://127.0.0.1:8080
    version: 0.0.1
''');
      expect(parsed['name'], 'wallet_core_flutter');
      expect(parsed['environment'], {'sdk': '^3.12.0', 'flutter': '>=3.44.0'});
      expect(parsed['dependencies'], {
        'wallet_core_flutter_bindings': {
          'hosted': 'http://127.0.0.1:8080',
          'version': '0.0.1',
        },
      });
    });

    test('a `hosted:` value keeps the `://` of its URL', () {
      final parsed = parseMiniYaml('hosted: http://127.0.0.1:53219\n');
      expect(parsed['hosted'], 'http://127.0.0.1:53219');
    });

    test('block sequence indented under its key', () {
      final parsed = parseMiniYaml('''
workspace:
    - packages/wallet_core_flutter
    - tools/packaging_eval
''');
      expect(parsed['workspace'], [
        'packages/wallet_core_flutter',
        'tools/packaging_eval',
      ]);
    });

    test('block sequence at the key\'s own indentation', () {
      // The root workspace pubspec writes it this way.
      final parsed = parseMiniYaml('''
workspace:
- packages/wallet_core_flutter
- packages/wallet_core_flutter_bindings
version: 0.0.1
''');
      expect(parsed['workspace'], [
        'packages/wallet_core_flutter',
        'packages/wallet_core_flutter_bindings',
      ]);
      expect(parsed['version'], '0.0.1');
    });

    test('sequence of mappings', () {
      final parsed = parseMiniYaml('''
plugins:
  - name: alpha
    path: android
  - name: beta
    path: ios
''');
      expect(parsed['plugins'], [
        {'name': 'alpha', 'path': 'android'},
        {'name': 'beta', 'path': 'ios'},
      ]);
    });

    test('folded `>-` block scalar joins its lines with spaces', () {
      final parsed = parseMiniYaml('''
description: >-
  Measurement harness shared by the two packaging evaluations.
  Build-time tooling; nothing here ships.
publish_to: none
''');
      expect(
        parsed['description'],
        'Measurement harness shared by the two packaging evaluations. '
        'Build-time tooling; nothing here ships.',
      );
      expect(parsed['publish_to'], 'none');
    });

    test('literal `|` block scalar keeps its newlines', () {
      final parsed = parseMiniYaml('''
notes: |
  first
  second
''');
      expect(parsed['notes'], 'first\nsecond');
    });

    test('comments are stripped, whole-line and trailing', () {
      final parsed = parseMiniYaml('''
# the package name
name: wcf_tool_packaging_eval  # not published
version: 0.0.1
''');
      expect(parsed, {'name': 'wcf_tool_packaging_eval', 'version': '0.0.1'});
    });

    test('a `#` inside a quoted scalar is not a comment', () {
      final parsed = parseMiniYaml('sha: "abc#def"\n');
      expect(parsed['sha'], 'abc#def');
    });

    test('quoted scalars keep their text and stay strings', () {
      final parsed = parseMiniYaml('''
single: 'it''s quoted'
double: "a \\"quoted\\" word"
numeric_looking: "0.0.1"
''');
      expect(parsed['single'], "it's quoted");
      expect(parsed['double'], 'a "quoted" word');
      expect(parsed['numeric_looking'], '0.0.1');
    });

    test('plain scalars are typed: int, bool, null', () {
      final parsed = parseMiniYaml('''
size: 19721208
enabled: true
disabled: false
missing: null
tilde: ~
''');
      expect(parsed['size'], 19721208);
      expect(parsed['enabled'], isTrue);
      expect(parsed['disabled'], isFalse);
      expect(parsed['missing'], isNull);
      expect(parsed['tilde'], isNull);
    });

    test('an empty document is an empty map', () {
      expect(parseMiniYaml('\n# nothing\n'), isEmpty);
    });

    test('a pubspec.lock stanza parses to the shape the assertion reads', () {
      final parsed = parseMiniYaml('''
# Generated by pub
packages:
  wallet_core_flutter:
    dependency: "direct main"
    description:
      name: wallet_core_flutter
      sha256: "0123456789abcdef"
      url: "http://127.0.0.1:53219"
    source: hosted
    version: "0.0.1"
sdks:
  dart: ">=3.12.0 <4.0.0"
''');
      final packages = parsed['packages']! as Map<String, Object?>;
      final entry = packages['wallet_core_flutter']! as Map<String, Object?>;
      expect(entry['source'], 'hosted');
      expect(entry['version'], '0.0.1');
      expect(
        (entry['description']! as Map<String, Object?>)['url'],
        'http://127.0.0.1:53219',
      );
      expect(parsed['sdks'], {'dart': '>=3.12.0 <4.0.0'});
    });
  });

  group('MiniYamlException', () {
    test('flow sequences are refused, not guessed at', () {
      expect(
        () => parseMiniYaml('platforms: [android, ios]\n'),
        throwsA(
          isA<MiniYamlException>().having(
            (e) => e.message,
            'message',
            contains('flow collections'),
          ),
        ),
      );
    });

    test('flow mappings are refused', () {
      expect(
        () => parseMiniYaml('dep: {hosted: x}\n'),
        throwsA(isA<MiniYamlException>()),
      );
    });

    test('anchors and aliases are refused', () {
      expect(
        () => parseMiniYaml('base: &anchor value\n'),
        throwsA(
          isA<MiniYamlException>().having(
            (e) => e.message,
            'message',
            contains('anchors'),
          ),
        ),
      );
    });

    test('multi-document input is refused', () {
      expect(
        () => parseMiniYaml('---\nname: a\n'),
        throwsA(
          isA<MiniYamlException>().having(
            (e) => e.message,
            'message',
            contains('multi-document'),
          ),
        ),
      );
    });

    test('tab indentation is refused', () {
      expect(
        () => parseMiniYaml('a:\n\tb: c\n'),
        throwsA(
          isA<MiniYamlException>().having(
            (e) => e.message,
            'message',
            contains('tab'),
          ),
        ),
      );
    });

    test('a line that is not `key:` is refused, with its line number', () {
      expect(
        () => parseMiniYaml('name: a\nnot a mapping line\n'),
        throwsA(
          isA<MiniYamlException>()
              .having((e) => e.message, 'message', contains('expected `key:`'))
              .having((e) => e.line, 'line', 2),
        ),
      );
    });

    test('toString names the message and the line', () {
      expect(
        MiniYamlException('boom', 7).toString(),
        'MiniYamlException: boom (line 7)',
      );
    });
  });
}
