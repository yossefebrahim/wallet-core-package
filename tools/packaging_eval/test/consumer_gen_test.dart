// PRD §12.2 step 11: a fresh consumer app that depends on the three packages
// as hosted packages, never by path.
//
// Unofficial Dart/Flutter SDK for the open-source Trust Wallet Core library.
// Not affiliated with or endorsed by Trust Wallet.
//
// The acceptance test at the bottom is the harness's reason for existing: an
// evaluation that only ever tested `path:` has not tested what a consumer gets.
// It is tagged `slow` (about a minute: `flutter create` plus `flutter pub get`)
// but is not excluded from `melos run test`, and it skips only when `flutter`
// is not on PATH.

import 'dart:io';

import 'package:test/test.dart';
import 'package:wcf_tool_packaging_eval/consumer_gen.dart';
import 'package:wcf_tool_packaging_eval/host.dart';
import 'package:wcf_tool_packaging_eval/results.dart';

const _threePackages = {
  'wallet_core_flutter',
  'wallet_core_flutter_bindings',
  'wallet_core_flutter_native',
};

String _lock({
  required String url,
  String source = 'hosted',
  String extra = '',
}) =>
    '''
# Generated by pub
packages:
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
${[for (final name in _threePackages) '  $name:\n'
          '    dependency: transitive\n'
          '    description:\n'
          '      name: $name\n'
          '      sha256: "${'0' * 64}"\n'
          '      url: "$url"\n'
          '    source: $source\n'
          '    version: "0.0.1"\n'].join()}$extra
sdks:
  dart: ">=3.12.0 <4.0.0"
''';

void main() {
  group('assertHostedLock', () {
    test('all three hosted from the local repository, no path entry', () {
      final assertion = assertHostedLock(
        _lock(url: 'http://127.0.0.1:53219'),
        expectedPackages: _threePackages,
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isTrue, reason: assertion.problems.join('; '));
      expect(assertion.hostedPackages, _threePackages.toList()..sort());
      expect(assertion.pathPackages, isEmpty);
    });

    test('a path entry anywhere in the lock fails the assertion', () {
      final assertion = assertHostedLock(
        _lock(
          url: 'http://127.0.0.1:53219',
          extra:
              '  some_other_plugin:\n'
              '    dependency: transitive\n'
              '    description:\n'
              '      path: "../plugin"\n'
              '    source: path\n'
              '    version: "0.0.1"\n',
        ),
        expectedPackages: _threePackages,
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isFalse);
      expect(assertion.pathPackages, ['some_other_plugin']);
      expect(
        assertion.problems.single,
        contains('path dependencies in the lock: some_other_plugin'),
      );
    });

    test('a package resolved from another source fails', () {
      final assertion = assertHostedLock(
        _lock(url: 'http://127.0.0.1:53219', source: 'path'),
        expectedPackages: _threePackages,
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isFalse);
      expect(
        assertion.problems,
        contains(
          'wallet_core_flutter resolved from source `path`, not `hosted`',
        ),
      );
    });

    test('a package resolved from pub.dev rather than the local URL fails', () {
      final assertion = assertHostedLock(
        _lock(url: 'https://pub.dev'),
        expectedPackages: _threePackages,
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isFalse);
      expect(
        assertion.problems,
        contains(
          'wallet_core_flutter resolved from `https://pub.dev`, not '
          '`http://127.0.0.1:53219`',
        ),
      );
    });

    test('a package missing from the lock fails', () {
      final assertion = assertHostedLock(
        _lock(url: 'http://127.0.0.1:53219'),
        expectedPackages: {..._threePackages, 'wallet_core_flutter_absent'},
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isFalse);
      expect(
        assertion.problems,
        contains('wallet_core_flutter_absent is not in the lock at all'),
      );
    });

    test('a lock with no packages map fails rather than passing vacuously', () {
      final assertion = assertHostedLock(
        'sdks:\n  dart: ">=3.12.0 <4.0.0"\n',
        expectedPackages: _threePackages,
        hostedUrl: 'http://127.0.0.1:53219',
      );
      expect(assertion.ok, isFalse);
      expect(assertion.problems.single, contains('no `packages` map'));
    });
  });

  group('excerptLock', () {
    test('lifts the requested stanzas verbatim and stops at the next key', () {
      final excerpt = excerptLock(
        _lock(url: 'http://127.0.0.1:53219'),
        _threePackages,
      );
      for (final name in _threePackages) {
        expect(excerpt, contains('  $name:\n'));
      }
      expect(excerpt, contains('    source: hosted'));
      expect(excerpt, isNot(contains('  flutter:')));
      expect(excerpt, isNot(contains('sdks:')));
    });
  });

  group('generateHostedConsumer (PRD §12.2 step 11)', () {
    test(
      'a fresh app resolves all three packages hosted from loopback, with no '
      'path entry',
      () async {
        if (flutterPath() == null) {
          markTestSkipped('flutter is not on PATH');
          return;
        }

        final outDirectory = scratchDirectory('wcf-consumer-gen-test-');
        addTearDown(() {
          if (outDirectory.existsSync()) {
            outDirectory.deleteSync(recursive: true);
          }
        });
        expect(
          outDirectory.path,
          isNot(startsWith(repoRoot().path)),
          reason: 'a generated consumer app never lands in the repository',
        );

        final outcome = await generateHostedConsumer(
          outDirectory: outDirectory,
        );

        final row = outcome.rows.single;
        expect(
          row.status,
          CheckStatus.pass,
          reason: '${row.notes}\n${row.values}',
        );
        expect(row.check, 'consumer-gen');
        expect(row.values['hosted_packages'], _threePackages.toList()..sort());
        expect(row.values['path_packages'], isEmpty);
        final hostedUrl = row.values['hosted_url']! as String;
        expect(hostedUrl, startsWith('http://127.0.0.1:'));

        // The server saw a version query for each of the three names, so the
        // pub client really resolved them from loopback rather than a cache.
        final served = (row.values['routes_served']! as List<Object?>)
            .cast<String>();
        for (final name in _threePackages) {
          expect(served, contains('/api/packages/$name'));
        }

        // And the lock itself, read back from disk rather than from the row.
        final lock = File('${outcome.consumerDirectory!.path}/pubspec.lock');
        expect(lock.existsSync(), isTrue);
        final contents = lock.readAsStringSync();
        expect(contents, isNot(contains('source: path')));
        for (final name in _threePackages) {
          expect(contents, contains('  $name:'));
        }
        expect(contents, contains('url: "$hostedUrl"'));
        expect(outcome.lockExcerpt, contains('source: hosted'));
        for (final name in _threePackages) {
          expect(outcome.lockExcerpt, contains('  $name:'));
        }
      },
      tags: ['slow'],
      timeout: const Timeout(Duration(minutes: 10)),
    );
  });
}
